// Bakes the build identity (rn-motion-ui version + git short sha) into
// storybook/native/.rnstorybook/build-info.ts so the on-device storybook can
// show which APK/build is running next to the dark-mode switch. Runs as part
// of `bun run storybook-generate` (CI apk job + local builds alike); the
// output is gitignored, so it is always regenerated from the checked-out
// commit. Falls back to 'dev' when not in a git checkout.
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const uiPkg = JSON.parse(readFileSync(resolve(root, 'packages/ui/package.json'), 'utf8'));

let sha = 'dev';
try {
  sha = execFileSync('git', ['rev-parse', '--short', 'HEAD'], { cwd: root })
    .toString()
    .trim();
} catch {
  // Not a git checkout (e.g. a published tarball) — label the build 'dev'.
}

const outDir = resolve(root, 'storybook/native/.rnstorybook');
mkdirSync(outDir, { recursive: true });
writeFileSync(
  resolve(outDir, 'build-info.ts'),
  [
    '// GENERATED by scripts/bake-build-info.mjs — do not edit.',
    'export const BUILD_INFO = {',
    `  version: ${JSON.stringify(uiPkg.version)},`,
    `  sha: ${JSON.stringify(sha)},`,
    '} as const;',
    '',
  ].join('\n'),
);
console.log(`baked build-info: rn-motion-ui@${uiPkg.version} · ${sha}`);
